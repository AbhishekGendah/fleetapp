export const VEHICLE_MAKES: readonly string[] = Object.keys(VEHICLE_MODELS);

function sameName(left: string, right: string): boolean {
  return left.localeCompare(right, undefined, { sensitivity: "base" }) === 0;
}

/** The list's own spelling of a name typed in any case, or null if it is not listed. */
export function listedName(names: readonly string[], typed: string): string | null {
  const trimmed = typed.trim();
  return names.find((name) => sameName(name, trimmed)) ?? null;
}

/** The models listed for a make, however its name was typed. Empty for a make not listed. */
export function modelsForMake(make: string): readonly string[] {
  const listedMake = listedName(VEHICLE_MAKES, make);
  return listedMake ? (VEHICLE_MODELS[listedMake] ?? []) : [];
}
